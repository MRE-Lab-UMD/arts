  /// Scratch for the configuration Ruckig just produced, used by the Cartesian speed
  /// governor. A member only so that the governor allocates nothing.
  Eigen::VectorXd q_written_;
  /// Consecutive cycles in which IK missed tolerance. Reported, but NOT itself a fault:
