  realtime_tools::RealtimeBuffer<geometry_msgs::msg::TwistStamped> target_velocity_buffer_;
  std::atomic<std::uint64_t> velocity_seq_{0};
  std::uint64_t consumed_velocity_seq_{0};
  rclcpp::Time last_velocity_stamp_;
  Eigen::Matrix<double, 6, 1> twist_ff_base_{Eigen::Matrix<double, 6, 1>::Zero()};
  /// Tip position of the current reference, for the rate-mode feedforward fade.
  Eigen::Vector3d target_position_{Eigen::Vector3d::Zero()};
  /// Rate mode: feedforward weight from Ruckig's acceleration saturation (0..1).
  double ff_saturation_weight_{1.0};
  /// Rate mode: the joint feedforward's own acceleration and jerk, for its feasibility.
  std::array<double, kMaxJoints> last_ff_velocity_{};
  std::array<double, kMaxJoints> ff_acceleration_{};
  std::array<double, kMaxJoints> ff_jerk_{};
  Eigen::VectorXd qd_target_;

  // -- task-layer QP and RCM (decision 17) --------------------------------------------
  TaskQp task_qp_;
  pinocchio::Data::Matrix6x jacobian_base_;  // tip Jacobian, base_frame axes
  TaskQp::Vector6 task_velocity_;
  TaskQp::Vector6 task_weights_;
  Eigen::VectorXd qd_lower_;
  Eigen::VectorXd qd_upper_;
  Eigen::VectorXd qd_qp_;
  Eigen::Matrix<double, 3, Eigen::Dynamic> shaft_point_jacobian_;
  Eigen::Matrix3d r_base_t_{Eigen::Matrix3d::Identity()};
  Eigen::Vector3d rcm_axis_{Eigen::Vector3d::UnitZ()};
  bool rcm_rows_fresh_{false};
  Eigen::VectorXd q_posture_;  // posture reference: joints at activation / last RCM switch
  Eigen::VectorXd qd_rest_;
  Eigen::Vector3d shaft_axis_{Eigen::Vector3d::UnitZ()};  // in the tip frame, unit
  pinocchio::SE3 target_pose_;  // the current reference, base->tip

  /// RT-owned RCM state. The point is kept after the RCM is turned off so rcm_state keeps
  /// reporting the deviation from it.
  bool rcm_enabled_{false};
  double last_insertion_depth_{0.10};  // m, RT thread only
  Eigen::Vector3d rcm_point_;
  bool rcm_fault_{false};
  bool qp_failed_{false};
  RcmGeometry measured_rcm_{};
  /// Read by the tool-tip offset service (the offset defines the shaft, so it is frozen
  /// while the RCM is on).
  std::atomic<bool> rcm_enabled_flag_{false};

  /// set_rcm handshake: the service writes a request and bumps the counter, the control
  /// cycle evaluates it against the MEASURED arm, writes the reply and publishes the reply
  /// counter; the service waits for it. The decision needs the arm's current shaft, which
  /// only the control thread may compute (it owns data_ and the model's tip placement).
  struct RcmRequest
  {
    bool enable{false};
    bool from_current_shaft{false};
    double insertion_depth{0.0};
    Eigen::Vector3d point{Eigen::Vector3d::Zero()};
  };
  struct RcmReply
  {
    bool success{false};
    std::array<char, 200> message{};
    Eigen::Vector3d point{Eigen::Vector3d::Zero()};
    double deviation{0.0};
    double insertion_depth{0.0};
  };
  realtime_tools::RealtimeBuffer<RcmRequest> rcm_request_buffer_;
  std::atomic<std::uint64_t> rcm_request_seq_{0};
  std::uint64_t consumed_rcm_request_seq_{0};
  RcmReply rcm_reply_;
  std::atomic<std::uint64_t> rcm_reply_seq_{0};
  std::mutex rcm_service_mutex_;
  rclcpp::Service<arts_interfaces::srv::SetRcm>::SharedPtr set_rcm_srv_;

  /// After an RCM switch the reference is ignored until a newer one arrives (SetRcm.srv).
  bool switch_hold_{false};
  std::uint64_t switch_reference_seq_{0};

  std::shared_ptr<rclcpp::Publisher<arts_interfaces::msg::RcmState>> rcm_state_pub_;
  std::unique_ptr<realtime_tools::RealtimePublisher<arts_interfaces::msg::RcmState>>
    rcm_state_rt_;
  arts_interfaces::msg::RcmState rcm_state_msg_;

  // -- command state -------------------------------------------------------------------
  /// Whether the internal state has been aligned with the arm since the last activation.
  /// Nothing may be commanded before it has, or the first cycle steps from wherever the
  /// previous session left off.
  bool seeded_{false};
  /// Joint configuration the arm is currently commanded to, i.e. Ruckig's last output
  /// scattered back into model order. Both the Cartesian rate bound and the IK seed are
  /// anchored to this, which is what keeps the tool-space speed limit honest.
  Eigen::VectorXd q_command_;

  // -- published state (decision 18) ---------------------------------------------------
  /// <arm>/tool_tip_state: FK of the MEASURED joints each cycle; twist by differencing.
  /// <arm>/joint_command: a copy of what was written this cycle. Both messages are sized at
  /// configure and copied by try_publish, so the cycle does not allocate.
  std::shared_ptr<rclcpp::Publisher<arts_interfaces::msg::ToolTipState>> tool_tip_state_pub_;
  std::unique_ptr<realtime_tools::RealtimePublisher<arts_interfaces::msg::ToolTipState>>
    tool_tip_state_rt_;
  arts_interfaces::msg::ToolTipState tool_tip_state_msg_;
  std::shared_ptr<rclcpp::Publisher<sensor_msgs::msg::JointState>> joint_command_pub_;
  std::unique_ptr<realtime_tools::RealtimePublisher<sensor_msgs::msg::JointState>>
    joint_command_rt_;
  sensor_msgs::msg::JointState joint_command_msg_;
  pinocchio::SE3 last_tip_pose_;
